"""Writes the upload guide (titles, descriptions, schedule) for rendered Shorts: python3 guide.py <shorts dir>"""
import json, sys, os
d = sys.argv[1]
meta = json.load(open(os.path.join(d, "meta.json")))
out = ["# คลิป Shorts โจทย์ประจำวัน", "",
       "คลิปละ 1 วัน ชื่อไฟล์คือวันที่ที่ควรลง โจทย์ในคลิปตรงกับโจทย์ประจำวันในเกมวันนั้นพอดี", "",
       "## วิธีอัปและตั้งเวลา (ครั้งเดียวได้ทั้งเดือน)", "",
       "1. เปิด studio.youtube.com บนคอมพิวเตอร์ กด **สร้าง** แล้วเลือก **อัปโหลดวิดีโอ**",
       "2. ลากไฟล์ .mp4 ทั้งหมดเข้าไปพร้อมกันได้สูงสุด 15 ไฟล์ต่อรอบ (ทำ 2 รอบ)",
       "3. แต่ละคลิป: คัดลอก **ชื่อ** และ **คำอธิบาย** จากตารางด้านล่างไปวาง เลือก **ไม่ใช่ เนื้อหานี้ไม่ได้สร้างมาเพื่อเด็ก**",
       "4. หน้า **ระดับการมองเห็น** เลือก **กำหนดเวลา** แล้วตั้งวันตามชื่อไฟล์ เวลา 18:00 น.",
       "", "ลิงก์ในคำอธิบายของ Shorts กดไม่ได้บนมือถือ ให้ใส่ลิงก์เกมในคำอธิบายช่อง และปักหมุดคอมเมนต์แรกเป็นลิงก์ของวันนั้นด้วย ท้ายคลิปมีที่อยู่เว็บขึ้นอยู่แล้ว", ""]
for m in meta:
    link = f"https://rochano.github.io/chess/?puzzle={m['key']}&utm_source=youtube&utm_medium=shorts&utm_campaign=puzzle"
    side_goal = m["title"].split(": ", 1)[1].split(" หาเจอไหม")[0]
    desc = (f"โจทย์หมากรุกประจำวัน #{m['no']} ({m['date']})\n{side_goal} หาเจอไหม? พิมพ์คำตอบในคอมเมนต์ได้เลย\n\n"
            f"ลองแก้เองในเกม: {link}\nเล่นหมากรุกฟรี ไม่ต้องสมัคร มีบทฝึกสำหรับมือใหม่\n\n#หมากรุก #chess #chesspuzzle #โจทย์หมากรุก")
    out += [f"## {m['date']} · {m['file']}", "", "**ชื่อ**", "```", m["title"], "```", "**คำอธิบาย**", "```", desc, "```", ""]
open(os.path.join(d, "README.md"), "w").write("\n".join(out))
print(len(meta))
